import { PGlite } from '@electric-sql/pglite';
import { createHash } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import test from 'node:test';

test('prova única de recusa não libera execução incerta nem reserva alheia ou preexistente', async () => {
 const db = new PGlite();
 const owner='00000000-0000-4000-8000-000000000001',other='00000000-0000-4000-8000-000000000002';
 const project='00000000-0000-4000-8000-000000000003',otherProject='00000000-0000-4000-8000-000000000004';
 const id=n=>`10000000-0000-4000-8000-${String(n).padStart(12,'0')}`;
 const prompt='a'.repeat(64),secret='12'.repeat(32),wrong='34'.repeat(32);
 const proof=createHash('sha256').update(Buffer.from(secret,'hex')).digest('hex');
 const badProof=createHash('sha256').update(Buffer.from(wrong,'hex')).digest('hex');
 try {
  await db.exec(`create role anon; create role authenticated; create schema auth; create schema storage;
   create table auth.users(id uuid primary key);
   create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
   grant usage on schema auth,storage to authenticated,anon; grant execute on function auth.uid() to authenticated,anon;
   create table public.projects(id uuid primary key,owner_id uuid not null references auth.users(id));
   alter table public.projects enable row level security; grant select on public.projects to authenticated;
   create policy project_select on public.projects for select to authenticated using(owner_id=auth.uid());
   create table public.agent_attempts(id uuid primary key,owner_id uuid,project_id uuid,state text);
   create table public.image_tool_reservations(id uuid primary key,owner_id uuid,project_id uuid,agent_attempt_id uuid,state text);
   create table public.image_consent_declarations(reservation_id uuid,owner_id uuid);
   create table public.image_tool_executions(id uuid primary key default gen_random_uuid(),owner_id uuid,reservation_id uuid,asset_id uuid default gen_random_uuid(),state text default 'running');
   create table storage.buckets(id text primary key,name text,public boolean,file_size_limit integer,allowed_mime_types text[]);
   create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text,name text);
   alter table storage.objects enable row level security; grant select,insert,update,delete on storage.objects to authenticated;`);
  for(const file of ['20261106000018_exploration_images.sql','20261106000019_exploration_feedback.sql','20261106000020_exploration_batches.sql','20261106000023_exploration_review_gate.sql','20261106000025_exploration_rejection_proof.sql'])
   await db.exec(await readFile(new URL(`../../supabase/migrations/${file}`,import.meta.url),'utf8'));
  await db.query('insert into auth.users values ($1),($2)',[owner,other]);
  await db.query('insert into public.projects values ($1,$2),($3,$4)',[project,owner,otherProject,other]);
  await db.exec('set role authenticated');
  const actor=async value=>db.query("select set_config('request.jwt.claim.sub',$1,false)",[value]);
  const reserve=async (image,digest=proof)=> (await db.query('select * from public.reserve_exploration_image_proven($1,$2,$3,$4)',[project,image,prompt,digest])).rows[0];
  const batched=async (image,digest=proof)=> (await db.query('select * from public.reserve_exploration_image_batched_proven($1,$2,$3,$4,1,$5)',[project,image,prompt,id(99),digest])).rows[0];
  const reject=(image,value=secret,scope=project)=>db.query('select public.reject_exploration_image($1,$2,$3)',[scope,image,value]);
  const complete=(image,value=secret,scope=project)=>db.query('select public.complete_exploration_image_proven($1,$2,$3)',[scope,image,value]);
  await actor(owner);
  assert.deepEqual(await reserve(id(1)),{state:'running',is_new:true});
  await assert.rejects(db.query('select * from public.exploration_rejection_proofs'));
  await assert.rejects(db.query('update public.exploration_rejection_proofs set digest=$1',[badProof]));
  await assert.rejects(db.query("select public.finish_exploration_image_internal($1,$2,'completed')",[project,id(1)]));
  await db.query('insert into storage.objects(bucket_id,name) values ($1,$2)',['compor-exploration-images',`${owner}/${project}/${id(1)}.png`]);
  await assert.rejects(db.query("select public.finish_exploration_image($1,$2,'completed')",[project,id(1)]),'an uploaded object alone cannot finalize protected work');
  await assert.rejects(complete(id(1),wrong));
  await assert.rejects(reject(id(1),wrong));
  await assert.rejects(reject(id(1),secret,otherProject));
  await actor(other);await assert.rejects(reject(id(1)));await actor(owner);
  assert.deepEqual(await reserve(id(1),badProof),{state:'running',is_new:false});
  await assert.rejects(reject(id(1),wrong),'repeated reservation cannot replace the original digest');
  assert.equal((await reject(id(1))).rows[0].reject_exploration_image,true);
  await assert.rejects(reject(id(1)),'proof cannot be replayed');
  assert.deepEqual(await reserve(id(1)),{state:'rejected',is_new:false});
  assert.deepEqual(await batched(id(2)),{state:'running',is_new:true});
  assert.deepEqual(await batched(id(3)),{state:'busy',is_new:false});
  await reject(id(2));
  assert.deepEqual(await batched(id(3)),{state:'running',is_new:true},'a confirmed refusal releases its batch position');
  assert.deepEqual(await batched(id(4)),{state:'busy',is_new:false});
  await db.query("select public.finish_exploration_image($1,$2,'unknown')",[project,id(3)]);
  await assert.rejects(reject(id(3)),'knowledge of a proof must not release unknown');
  assert.deepEqual(await reserve(id(4)),{state:'blocked',is_new:false});
  await db.query('insert into storage.objects(bucket_id,name) values ($1,$2)',['compor-exploration-images',`${owner}/${project}/${id(3)}.png`]);
  await assert.rejects(db.query("select public.finish_exploration_image($1,$2,'completed')",[project,id(3)]));
  assert.equal((await complete(id(3))).rows[0].complete_exploration_image_proven,true);
  await assert.rejects(complete(id(3)),'completion proof cannot be replayed');
  assert.deepEqual(await reserve(id(7)),{state:'running',is_new:true});
  await assert.rejects(complete(id(7)),'missing bytes must not consume the proof');
  assert.equal((await reject(id(7))).rows[0].reject_exploration_image,true);
  assert.deepEqual(await reserve(id(8)),{state:'running',is_new:true});
  await db.query('insert into storage.objects(bucket_id,name) values ($1,$2)',['compor-exploration-images',`${owner}/${project}/${id(8)}.png`]);
  await db.exec('reset role');await db.query('update public.projects set owner_id=$1 where id=$2',[other,project]);await db.exec('set role authenticated');await actor(owner);
  await assert.rejects(complete(id(8)),'completion must recheck current ownership');
  await assert.rejects(reject(id(8)),'rejection must recheck current ownership');
  await db.exec('reset role');await db.query('update public.projects set owner_id=$1 where id=$2',[owner,project]);await db.exec('set role authenticated');await actor(owner);
  assert.equal((await complete(id(8))).rows[0].complete_exploration_image_proven,true,'failed ownership check rolls back proof consumption');
  // Simulate a legacy reservation that existed before migration. A subsequent
  // protected reservation must not attach a new secret or start generation.
  await db.exec('reset role');
  await db.query("insert into public.exploration_images(id,owner_id,project_id,prompt_digest,state) values($1,$2,$3,$4,'running')",[id(5),other,otherProject,prompt]);
  await db.exec('set role authenticated');
  await actor(other);
  const legacy=id(5);
  await assert.rejects(db.query('select * from public.reserve_exploration_image($1,$2,$3)',[otherProject,id(6),prompt]),'legacy reserve cannot create new unprotected work');
  const existing=await db.query('select * from public.reserve_exploration_image_proven($1,$2,$3,$4)',[otherProject,legacy,prompt,proof]);
  assert.deepEqual(existing.rows,[{state:'running',is_new:false}]);
  await assert.rejects(reject(legacy,secret,otherProject));
  await db.query('insert into storage.objects(bucket_id,name) values ($1,$2)',['compor-exploration-images',`${other}/${otherProject}/${legacy}.png`]);
  await assert.rejects(db.query("select public.finish_exploration_image($1,$2,'completed')",[otherProject,legacy]));
  await db.query("select public.finish_exploration_image($1,$2,'unknown')",[otherProject,legacy]);
  await assert.rejects(db.query("select public.finish_exploration_image($1,$2,'completed')",[otherProject,legacy]));
  await db.exec('reset role; set role anon');
  await assert.rejects(db.query('select public.reject_exploration_image($1,$2,$3)',[project,id(1),secret]));
 } finally {await db.close();}
});
