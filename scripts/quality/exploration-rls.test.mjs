import { PGlite } from '@electric-sql/pglite';
import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import test from 'node:test';
test('sinais e gerações exploratórias respeitam isolamento e reserva entre fluxos', async () => {
const db = new PGlite();
try {
await db.exec(`
  create role anon; create role authenticated;
  create schema auth; create schema storage;
  create table auth.users(id uuid primary key);
  create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
  grant usage on schema auth,storage to authenticated,anon;
  grant execute on function auth.uid() to authenticated,anon;
  create table public.projects(id uuid primary key,owner_id uuid not null references auth.users(id));
  alter table public.projects enable row level security;
  grant select on public.projects to authenticated;
  create policy project_select on public.projects for select to authenticated using (owner_id=auth.uid());
  create table public.agent_attempts(id uuid primary key,owner_id uuid,project_id uuid,state text);
  create table public.image_tool_reservations(id uuid primary key,owner_id uuid,project_id uuid,agent_attempt_id uuid,state text);
  create table public.image_consent_declarations(reservation_id uuid,owner_id uuid);
  create table public.image_tool_executions(id uuid primary key default gen_random_uuid(),owner_id uuid,reservation_id uuid,asset_id uuid default gen_random_uuid(),state text default 'running');
  create table storage.buckets(id text primary key,name text,public boolean,file_size_limit integer,allowed_mime_types text[]);
  create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text,name text);
  alter table storage.objects enable row level security;
  grant select,insert,update,delete on storage.objects to authenticated;
`);
for (const file of ['20261106000017_reference_signals.sql','20261106000018_exploration_images.sql','20261106000020_exploration_batches.sql']) await db.exec(await readFile(new URL(`../../supabase/migrations/${file}`, import.meta.url),'utf8'));
const u1='00000000-0000-4000-8000-000000000001',u2='00000000-0000-4000-8000-000000000002',p1='00000000-0000-4000-8000-000000000003',p2='00000000-0000-4000-8000-000000000004',i1='00000000-0000-4000-8000-000000000005',i2='00000000-0000-4000-8000-000000000006';
await db.query(`insert into auth.users values ($1),($2)`,[u1,u2]);
await db.query(`insert into projects values ($1,$2),($3,$4)`,[p1,u1,p2,u2]);
await db.exec(`set role authenticated;`);
await db.query(`select set_config('request.jwt.claim.sub',$1,false)`,[u1]);
await db.query('insert into public.reference_signals(id,project_id,origin_url,board,action,comment) values ($1,$2,$3,$4,$5,$6)',[i1,p1,'https://www.pinterest.com/pin/123/','behance/typography','selected','']);
const digest='a'.repeat(64);
assert.deepEqual((await db.query('select * from public.reserve_exploration_image($1,$2,$3)',[p1,i1,digest])).rows,[{state:'running',is_new:true}]);
assert.deepEqual((await db.query('select * from public.reserve_exploration_image($1,$2,$3)',[p1,i1,digest])).rows,[{state:'running',is_new:false}]);
assert.deepEqual((await db.query('select * from public.reserve_exploration_image($1,$2,$3)',[p1,i2,digest])).rows,[{state:'busy',is_new:false}]);
await assert.rejects(db.query('select public.finish_exploration_image($1,$2,$3)',[p1,i1,'completed']));
await db.query('insert into storage.objects(bucket_id,name) values ($1,$2)',['compor-exploration-images',`${u1}/${p1}/${i1}.png`]);
await db.query('select public.finish_exploration_image($1,$2,$3)',[p1,i1,'completed']);
const batch='00000000-0000-4000-8000-000000000012';
assert.deepEqual((await db.query('select * from public.reserve_exploration_image_batched($1,$2,$3,$4,$5)',[p1,i2,digest,batch,1])).rows,[{state:'running',is_new:true}]);
assert.deepEqual((await db.query('select ordinal,batch_id,batch_position from public.exploration_images where id=$1',[i2])).rows,[{ordinal:2,batch_id:batch,batch_position:1}]);
assert.deepEqual((await db.query('select * from public.reserve_exploration_image_batched($1,$2,$3,$4,$5)',[p1,i2,digest,batch,1])).rows,[{state:'running',is_new:false}]);
await assert.rejects(db.query('select * from public.reserve_exploration_image_batched($1,$2,$3,$4,$5)',[p1,i2,digest,batch,2]));
await db.exec('reset role');
const attempt='00000000-0000-4000-8000-000000000007',reservation='00000000-0000-4000-8000-000000000008';
await db.query('insert into public.agent_attempts values ($1,$2,$3,$4)',[attempt,u1,p1,'started']);
await db.query('insert into public.image_tool_reservations values ($1,$2,$3,$4,$5)',[reservation,u1,p1,attempt,'reserved']);
await db.query('insert into public.image_consent_declarations values ($1,$2)',[reservation,u1]);
await db.exec('set role authenticated');
assert.deepEqual((await db.query('select * from public.claim_image_tool_execution($1)',[reservation])).rows,[{execution_id:null,asset_id:null,state:'busy',is_new:false}]);
await db.query('insert into storage.objects(bucket_id,name) values ($1,$2)',['compor-exploration-images',`${u1}/${p1}/${i2}.png`]);
await db.query('select public.finish_exploration_image($1,$2,$3)',[p1,i2,'completed']);
const i3='00000000-0000-4000-8000-000000000009';
assert.deepEqual((await db.query('select * from public.reserve_exploration_image($1,$2,$3)',[p1,i3,digest])).rows,[{state:'busy',is_new:false}]);
assert.equal((await db.query('select * from public.claim_image_tool_execution($1)',[reservation])).rows[0].is_new,true);
assert.deepEqual((await db.query('select * from public.reserve_exploration_image($1,$2,$3)',[p1,i3,digest])).rows,[{state:'busy',is_new:false}]);
await db.query(`select set_config('request.jwt.claim.sub',$1,false)`,[u2]);
assert.equal((await db.query('select * from public.exploration_images')).rows.length,0);
assert.equal((await db.query('select * from storage.objects')).rows.length,0);
assert.equal((await db.query('select * from public.reference_signals')).rows.length,0);
await assert.rejects(db.query('insert into public.reference_signals(id,project_id,origin_url,board,action,comment) values ($1,$2,$3,$4,$5,$6)',[i2,p1,'https://www.pinterest.com/pin/123/','behance/typography','rejected','']));
await assert.rejects(db.query('select * from public.reserve_exploration_image($1,$2,$3)',[p1,i1,digest]));
await assert.rejects(db.query('insert into storage.objects(bucket_id,name) values ($1,$2)',['compor-exploration-images',`${u1}/${p1}/${i1}.png`]));
const i4='00000000-0000-4000-8000-000000000010',i5='00000000-0000-4000-8000-000000000011';
assert.deepEqual((await db.query('select * from public.reserve_exploration_image_batched($1,$2,$3,$4,$5)',[p2,i4,digest,batch,1])).rows,[{state:'running',is_new:true}]);
await db.query('insert into storage.objects(bucket_id,name) values ($1,$2)',['compor-exploration-images',`${u2}/${p2}/${i4}.png`]);
await db.query('select public.finish_exploration_image($1,$2,$3)',[p2,i4,'completed']);
await assert.rejects(db.query('select * from public.reserve_exploration_image_batched($1,$2,$3,$4,$5)',[p2,i5,digest,batch,1]));
assert.equal((await db.query('select * from public.exploration_images where id=$1',[i5])).rows.length,0);
assert.deepEqual((await db.query('select * from public.reserve_exploration_image_batched($1,$2,$3,$4,$5)',[p2,i5,digest,batch,2])).rows,[{state:'running',is_new:true}]);
await db.query('select public.finish_exploration_image($1,$2,$3)',[p2,i5,'unknown']);
assert.deepEqual((await db.query('select * from public.reserve_exploration_image($1,$2,$3)',[p2,'00000000-0000-4000-8000-000000000014',digest])).rows,[{state:'blocked',is_new:false}]);
} finally { await db.close(); }
});
