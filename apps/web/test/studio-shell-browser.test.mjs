import test from 'node:test';
import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import { mkdir, writeFile, rm, readFile } from 'node:fs/promises';
import { spawn } from 'node:child_process';
import { createServer } from 'node:net';
import { chromium } from 'playwright-core';
import { stopApp, waitForApp } from './wait-for-app.mjs';
import { isolateFixtureHmr } from './fixture-hmr.mjs';

const browserPath = process.env.BROWSER_EXECUTABLE_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const fixture = new URL('../app/studio-visual-test/', import.meta.url);
const pageSource = `'use client';
import {useState} from 'react';
import StudioShell,{CreativeBoard,StudioEmptyBoard,StudioChatPanel} from '../studio-shell';
export default function Preview(){
 const [stage,setStage]=useState('studio'),[message,setMessage]=useState(''),[art,setArt]=useState(false);
 return <StudioShell stage={stage} projectId="project-planilhas" projectTitle="Planilhas para a rotina" onNewProject={()=>setStage('projects')} onNavigate={setStage} onTabChange={()=>setStage('studio')} canOpenStudio userLabel="Mavi Almeida" basesCount={3} bases={<div><h2>Referências</h2><p>Três bases locais.</p></div>} marca={<div><h2>Marca do projeto</h2><p>Direção criativa local.</p></div>} viewingArt={art} onCloseArt={()=>setArt(false)} footer="Alterações ainda locais no navegador" canvas={<CreativeBoard title="Vamos encontrar a sua direção."><StudioEmptyBoard onStartIdea={()=>setMessage('Quero divulgar meu curso.')} onAddReference={()=>setMessage('referência')}/><button type="button" onClick={()=>setArt(true)}>Ver arte</button></CreativeBoard>} chat={<StudioChatPanel composer={<form onSubmit={event=>{event.preventDefault();setMessage('Enviada');}}><label className="studio-hint" htmlFor="test-message">Sua mensagem</label><textarea id="test-message" value={message} onChange={event=>setMessage(event.target.value)} placeholder="Peça um ajuste ou conte uma ideia…"/><div className="studio-composer-actions"><span className="studio-hint">Referências locais</span><button className="studio-button">Enviar</button></div></form>}><div className="studio-message" data-role="assistant"><span className="studio-message-label">Compor</span><p>O que você quer criar hoje? Pode me contar do seu jeito.</p></div></StudioChatPanel>}><p>Conteúdo da etapa {stage}</p></StudioShell>;
}`;
const navigationSource = `'use client';
import {useState} from 'react';
import StudioShell from '../../studio-shell';
import StudioNavigation from '../../studio-navigation';
export default function Preview(){
 const [projects,setProjects]=useState([{id:'project-planilhas',title:'Planilhas para a rotina'},{id:'project-outro',title:'Outro projeto'}]);
 const [projectId,setProjectId]=useState('project-planilhas');
 const project=projects.find(item=>item.id===projectId);
 return <StudioShell guided stage="studio" projectId={projectId} projectTitle={project.title} projects={projects} onOpenProject={next=>setProjectId(next.id)} sidebar={<StudioNavigation projectTitle={project.title} onRenameProject={async title=>setProjects(items=>items.map(item=>item.id===projectId?{...item,title}:item))} actions={[]}/>} canvas={<p>Quadro de {project.title}</p>}/>;
}`;

test('shell usa ativos originais, mantém navegação por teclado e permite explorar o quadro', { skip: !existsSync(browserPath), timeout: 90000 }, async t => {
  assert.equal(existsSync(fixture), false);
  await mkdir(fixture);
  await writeFile(new URL('page.jsx', fixture), pageSource);
  await mkdir(new URL('navigation/', fixture));
  await writeFile(new URL('navigation/page.jsx', fixture), navigationSource);
  const socket = createServer();
  await new Promise(resolve => socket.listen(0, '127.0.0.1', resolve));
  const port = socket.address().port;
  await new Promise(resolve => socket.close(resolve));
  const origin = `http://127.0.0.1:${port}`;
  const server = spawn(process.execPath, ['node_modules/next/dist/bin/next', 'dev', '-p', String(port), '-H', '127.0.0.1'], { stdio: ['ignore', 'pipe', 'pipe'], env: { ...process.env, SUPABASE_URL: '', SUPABASE_PUBLISHABLE_KEY: '' } });
  let serverLog = '';
  for (const stream of [server.stdout, server.stderr]) stream.on('data', data => { serverLog = (serverLog + data.toString()).slice(-4000); });
  let browser;
  t.after(async () => { try { await browser?.close(); } finally { try { await stopApp(server); } finally { await rm(fixture, { recursive: true, force: true }); } } });
  await waitForApp({url: `${origin}/studio-visual-test`, child: server, signal: t.signal, diagnostics: () => serverLog});
  browser = await chromium.launch({ executablePath: browserPath, headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 } });
  let phase = 'opening fixture';
  const errors = [], hmrFrames = [];
  page.on('websocket', socket => socket.on('framereceived', frame => {
    if (!socket.url().includes('/_next/')) return;
    try { const value = JSON.parse(String(frame.payload)); hmrFrames.push(value.type ?? value.action ?? 'unknown'); if (hmrFrames.length > 20) hmrFrames.shift(); } catch {}
  }));
  page.on('pageerror', error => { errors.push(error.message); t.diagnostic(`Erro em ${phase}; HMR=${hmrFrames.join(',')}: ${error.stack || error.message}`); });
  await isolateFixtureHmr(page, '/studio-visual-test');
  await page.goto(`${origin}/studio-visual-test`);
  await page.getByRole('heading', { name: 'Vamos encontrar a sua direção.' }).waitFor();
  const launcher = page.getByRole('button', { name: 'Abrir conversa', exact: true });
  assert.equal(await launcher.getAttribute('aria-expanded'), 'false');
  assert.equal(await page.getByRole('complementary', { name: 'Conversa com a IA' }).count(), 0);
  const fullCanvas = await page.locator('.studio-canvas-column').boundingBox();
  assert.equal(Math.round(fullCanvas.width), 1440, 'o quadro ocupa a área principal com a conversa recolhida');
  const launcherBounds = await launcher.boundingBox();
  await launcher.click();
  await page.waitForFunction(() => document.activeElement?.id === 'test-message');
  await page.evaluate(() => document.fonts.ready);
  const geometry = await page.evaluate(() => {
    const chat = document.querySelector('.studio-conversation').getBoundingClientRect();
    const canvas = document.querySelector('.studio-canvas-column').getBoundingClientRect();
    return { sidebar: document.querySelector('.studio-sidebar'), history: document.querySelector('[role="tab"]'), chat: Math.round(chat.width), chatCenter: chat.x + chat.width / 2, chatLeft: chat.x < canvas.x, font: getComputedStyle(document.querySelector('.compor-studio')).fontFamily, layout: document.querySelector('.compor-studio').dataset.layout, images: Array.from(document.querySelectorAll('.compor-studio img')).map(image => ({ src: image.getAttribute('src'), loaded: image.complete && image.naturalWidth > 0 })) };
  });
  assert.equal(geometry.sidebar, null);
  assert.equal(geometry.history, null);
  assert.equal(geometry.chat, Math.round(launcherBounds.width));
  assert.ok(Math.abs(geometry.chatCenter - (launcherBounds.x + launcherBounds.width / 2)) < 1, 'painel expandido permanece alinhado à barra');
  assert.equal(geometry.chatLeft, false);
  await page.locator('.studio-chat-messages').evaluate(element => {
    for (let index = 0; index < 30; index++) {
      const message = document.createElement('p');
      message.className = 'studio-message';
      message.textContent = `Mensagem longa ${index}`;
      element.append(message);
    }
  });
  const longChat = await page.evaluate(() => {
    const messages = document.querySelector('.studio-chat-messages');
    const composer = document.querySelector('.studio-chat-composer').getBoundingClientRect();
    return { scrollable: messages.scrollHeight > messages.clientHeight, bottom: composer.bottom, viewport: window.innerHeight };
  });
  assert.equal(longChat.scrollable, true, 'a conversa longa rola dentro do painel');
  assert.ok(longChat.bottom <= longChat.viewport, 'a caixa de mensagem permanece na tela');
  assert.equal(geometry.layout, 'b');
  assert.match(geometry.font, /Compor DM Sans/);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  const motion = await page.evaluate(() => {
    const icon = document.createElement('img'); icon.className = 'studio-batch-spinner'; document.body.append(icon);
    const animation = getComputedStyle(icon).animationName; icon.remove(); return animation;
  });
  assert.equal(motion, 'none', 'o contador permanece sem animação quando a pessoa pede movimento reduzido');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  assert.ok(geometry.images.every(image => image.loaded && image.src.startsWith('/studio/')));
  for (const name of ['brand-symbol.svg', 'brand-wordmark.svg', 'dot.svg', 'compor-avatar.svg']) assert.ok((await readFile(new URL(`../public/studio/${name}`, import.meta.url))).length > 100);
  const yellow = 'rgb(246, 213, 80)';
  const buttons = await page.locator('button').evaluateAll(nodes => nodes.map(button => ({ name: button.innerText.trim(), color: getComputedStyle(button).backgroundColor })));
  assert.equal(buttons.some(button => button.name === 'Baixar'), false, 'download belongs to review');
  assert.ok(buttons.every(button => button.color !== yellow));
  await page.getByRole('button', { name: 'Aumentar zoom' }).click();
  await page.getByRole('button', { name: 'Restaurar zoom a 100%' }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Restaurar zoom a 100%' }).innerText(), '110%');
  await page.getByRole('button', { name: 'Ver quadro todo' }).click();
  assert.notEqual(await page.getByRole('button', { name: 'Restaurar zoom a 100%' }).innerText(), '110%');
  await page.getByRole('button', { name: 'Restaurar zoom a 100%' }).click();
  await page.getByRole('button', { name: 'Divulgar meu curso' }).click();
  assert.equal(await page.getByLabel('Sua mensagem').inputValue(), 'Quero divulgar meu curso.');
  const before = await page.locator('.studio-canvas-column').boundingBox();
  await page.getByRole('button', { name: 'Bases (3)', exact: true }).click();
  await page.getByRole('dialog', { name: 'Bases' }).waitFor();
  const during = await page.locator('.studio-canvas-column').boundingBox();
  assert.equal(Math.round(before.x), Math.round(during.x));
  assert.equal(Math.round(before.width), Math.round(during.width));
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog', { name: 'Bases' }).count(), 0);
  assert.equal(await page.getByRole('button', { name: 'Bases (3)', exact: true }).evaluate(button => button === document.activeElement), true);
  await page.getByRole('button', { name: 'Marca', exact: true }).click();
  await page.getByRole('dialog', { name: 'Marca' }).waitFor();
  await page.mouse.click(during.x + 500, during.y + 80);
  assert.equal(await page.getByRole('dialog', { name: 'Marca' }).count(), 0);
  const navigationPage = await browser.newPage({viewport:{width:1440,height:960}});
  navigationPage.on('pageerror', error => errors.push(error.message));
  try {
    await isolateFixtureHmr(navigationPage, '/studio-visual-test/navigation');
    await navigationPage.goto(`${origin}/studio-visual-test/navigation`);
    const rail = navigationPage.getByRole('navigation', {name:'Projetos',exact:true});
    const first = rail.getByRole('button', {name:'Planilhas para a rotina',exact:true});
    const second = rail.getByRole('button', {name:'Outro projeto',exact:true});
    await first.waitFor();
    assert.equal(await first.getAttribute('aria-current'), 'page');
    await second.click();
    assert.equal(await second.getAttribute('aria-current'), 'page');
    assert.equal(await first.getAttribute('aria-current'), null);
    const rename = navigationPage.getByRole('button', {name:'Renomear projeto Outro projeto',exact:true});
    await rename.click();
    await navigationPage.getByLabel('Renomear', {exact:true}).fill('Projeto renomeado');
    await navigationPage.getByRole('button', {name:'Salvar nome',exact:true}).click();
    await navigationPage.getByRole('heading', {name:'Projeto renomeado',exact:true}).waitFor();
    assert.equal(await rail.getByRole('button', {name:'Projeto renomeado',exact:true}).getAttribute('aria-current'), 'page');
    const renamed = navigationPage.getByRole('button', {name:'Renomear projeto Projeto renomeado',exact:true});
    await renamed.click();
    await navigationPage.getByLabel('Renomear', {exact:true}).fill('Nome cancelado');
    await navigationPage.keyboard.press('Escape');
    assert.equal(await navigationPage.getByLabel('Renomear', {exact:true}).count(), 0);
    assert.equal(await navigationPage.getByRole('heading', {name:'Projeto renomeado',exact:true}).count(), 1);
    await renamed.focus();
    await navigationPage.keyboard.press('Escape');
    const expand = navigationPage.getByRole('button', {name:'Expandir menu',exact:true});
    assert.equal(await expand.getAttribute('aria-expanded'), 'false');
    assert.equal(await expand.evaluate(button=>button===document.activeElement), true);
  } finally { await navigationPage.close(); }
  await page.screenshot({ path: '/tmp/compor-layout-b.png', fullPage: false });
  await page.getByRole('button', { name: 'Recolher conversa', exact: true }).click();
  await page.getByRole('button', { name: 'Abrir conversa', exact: true }).waitFor();
  assert.equal(await page.locator('.compor-studio').getAttribute('data-layout'), 'c');
  const collapsedWidth = await page.locator('.studio-canvas-column').evaluate(element => element.getBoundingClientRect().width);
  assert.ok(collapsedWidth > 1200);
  await page.evaluate(() => {
    window.originalAnimationFrame = window.requestAnimationFrame;
    window.delayedFrames = [];
    window.requestAnimationFrame = callback => { window.delayedFrames.push(callback); return 1; };
  });
  await launcher.click();
  const collapseButton = page.getByRole('button', {name:'Recolher conversa',exact:true});
  await collapseButton.focus();
  await page.evaluate(() => {
    window.requestAnimationFrame = window.originalAnimationFrame;
    for (const callback of window.delayedFrames) callback(performance.now());
  });
  assert.equal(await collapseButton.evaluate(element => element === document.activeElement), true, 'a abertura não toma o foco já escolhido');
  await collapseButton.click();
  await launcher.waitFor();
  await page.screenshot({ path: '/tmp/compor-layout-c.png', fullPage: false });
  phase = 'reloading fixture';
  await page.reload();
  await page.getByRole('button', { name: 'Abrir conversa', exact: true }).waitFor();
  assert.equal(await page.locator('.compor-studio').getAttribute('data-layout'), 'c');
  await page.getByRole('button', { name: 'Abrir conversa', exact: true }).click();
  await page.getByRole('complementary', { name: 'Conversa com a IA' }).waitFor();
  assert.equal(await page.locator('.compor-studio').getAttribute('data-layout'), 'b');
  await page.getByRole('button', { name: 'Ver arte', exact: true }).click();
  assert.equal(await page.locator('.compor-studio').getAttribute('data-art'), 'open');
  assert.equal(await page.locator('.compor-studio').getAttribute('data-layout'), 'c');
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.compor-studio').getAttribute('data-art'), 'closed');
  assert.equal(await page.locator('.compor-studio').getAttribute('data-layout'), 'c');
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  const mobileCanvas = await page.locator('.studio-canvas-column').boundingBox();
  assert.equal(Math.round(mobileCanvas.width), 390);
  await page.getByRole('button', { name: 'Abrir conversa', exact: true }).click();
  const mobileChat = await page.evaluate(() => ({
    chat: document.querySelector('.studio-conversation').getBoundingClientRect().toJSON(),
    composerBottom: document.querySelector('.studio-chat-composer').getBoundingClientRect().bottom,
    viewport: window.innerHeight,
  }));
  assert.ok(mobileChat.chat.x >= 0 && mobileChat.chat.right <= 390 && mobileChat.chat.top >= 0 && mobileChat.chat.bottom <= 844, 'o painel flutuante cabe no viewport');
  assert.ok(mobileChat.composerBottom <= mobileChat.viewport, 'o compositor continua visível no celular');
  await page.getByLabel('Sua mensagem').fill('Rascunho preservado');
  await page.keyboard.press('Escape');
  await page.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === 'Abrir conversa');
  assert.equal(await page.getByRole('button', { name: 'Abrir conversa', exact: true }).evaluate(button => button === document.activeElement), true);
  await page.getByRole('button', { name: 'Abrir conversa', exact: true }).click();
  assert.equal(await page.getByLabel('Sua mensagem').inputValue(), 'Rascunho preservado');
  await page.getByRole('button', { name: 'Recolher conversa', exact: true }).click();
  await page.setViewportSize({ width: 742, height: 720 });
  assert.equal(Math.round((await page.locator('.studio-canvas-column').boundingBox()).width), 742);
  await page.getByRole('button', { name: 'Abrir conversa', exact: true }).click();
  const compactPanel = await page.getByRole('complementary', { name: 'Conversa com a IA' }).boundingBox();
  assert.ok(compactPanel.x >= 0 && compactPanel.x + compactPanel.width <= 742 && compactPanel.y >= 0 && compactPanel.y + compactPanel.height <= 720);
  const marca = await page.getByRole('button', { name: 'Marca', exact: true }).boundingBox();
  assert.ok(marca.x >= 0 && marca.x + marca.width <= 742);
  await page.screenshot({ path: '/tmp/compor-layout-mobile.png', fullPage: false });
  assert.deepEqual(errors, []);
});
