import test from 'node:test';
import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import { mkdir, writeFile, rm, readFile } from 'node:fs/promises';
import { spawn } from 'node:child_process';
import { once } from 'node:events';
import { createServer } from 'node:net';
import { chromium } from 'playwright-core';

const browserPath = process.env.BROWSER_EXECUTABLE_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const fixture = new URL('../app/studio-visual-test/', import.meta.url);
const pageSource = `'use client';
import {useState} from 'react';
import StudioShell,{CreativeBoard,StudioEmptyBoard,StudioChatPanel} from '../studio-shell';
export default function Preview(){
 const [stage,setStage]=useState('studio'),[message,setMessage]=useState(''),[title,setTitle]=useState('Planilhas para a rotina'),[art,setArt]=useState(false);
 return <StudioShell stage={stage} projectId="project-planilhas" projectTitle={title} pieceSubtitle="Post para divulgar seu curso / 1080 × 1350" projects={[{id:'project-planilhas',title:'Planilhas para a rotina'},{id:'project-outro',title:'Outro projeto'}]} onOpenProject={project=>setTitle(project.title)} onRenameProject={async next=>setTitle(next)} onNewProject={()=>setStage('projects')} onNavigate={setStage} onTabChange={()=>setStage('studio')} canOpenStudio userLabel="Mavi Almeida" basesCount={3} bases={<div><h2>Referências</h2><p>Três bases locais.</p></div>} marca={<div><h2>Marca do projeto</h2><p>Direção criativa local.</p></div>} onDownload={()=>{}} viewingArt={art} onCloseArt={()=>setArt(false)} footer="Alterações ainda locais no navegador" canvas={<CreativeBoard title="Vamos encontrar a sua direção."><StudioEmptyBoard onStartIdea={()=>setMessage('Quero divulgar meu curso.')} onAddReference={()=>setMessage('referência')}/><button type="button" onClick={()=>setArt(true)}>Ver arte</button></CreativeBoard>} chat={<StudioChatPanel composer={<form onSubmit={event=>{event.preventDefault();setMessage('Enviada');}}><label className="studio-hint" htmlFor="test-message">Sua mensagem</label><textarea id="test-message" value={message} onChange={event=>setMessage(event.target.value)} placeholder="Peça um ajuste ou conte uma ideia…"/><div className="studio-composer-actions"><span className="studio-hint">Referências locais</span><button className="studio-button">Enviar</button></div></form>}><div className="studio-message" data-role="assistant"><span className="studio-message-label">Compor</span><p>O que você quer criar hoje? Pode me contar do seu jeito.</p></div></StudioChatPanel>}><p>Conteúdo da etapa {stage}</p></StudioShell>;
}`;

test('shell usa ativos originais, mantém navegação por teclado e permite explorar o quadro', { skip: !existsSync(browserPath) }, async t => {
  assert.equal(existsSync(fixture), false);
  await mkdir(fixture);
  await writeFile(new URL('page.jsx', fixture), pageSource);
  t.after(() => rm(fixture, { recursive: true, force: true }));
  const socket = createServer();
  await new Promise(resolve => socket.listen(0, '127.0.0.1', resolve));
  const port = socket.address().port;
  await new Promise(resolve => socket.close(resolve));
  const origin = `http://127.0.0.1:${port}`;
  const server = spawn(process.execPath, ['node_modules/next/dist/bin/next', 'dev', '-p', String(port), '-H', '127.0.0.1'], { stdio: 'ignore', env: { ...process.env, SUPABASE_URL: '', SUPABASE_PUBLISHABLE_KEY: '' } });
  t.after(async () => { if (server.exitCode === null && server.signalCode === null) { server.kill('SIGTERM'); await once(server, 'exit'); } });
  const deadline = Date.now() + 30000;
  while (true) { try { if ((await fetch(origin)).ok) break; } catch {} if (Date.now() > deadline) throw Error('Next não iniciou.'); await new Promise(resolve => setTimeout(resolve, 200)); }
  const browser = await chromium.launch({ executablePath: browserPath, headless: true });
  t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${origin}/studio-visual-test`);
  await page.getByRole('heading', { name: 'Vamos encontrar a sua direção.' }).waitFor();
  await page.evaluate(() => document.fonts.ready);
  const geometry = await page.evaluate(() => {
    const chat = document.querySelector('.studio-conversation').getBoundingClientRect();
    const canvas = document.querySelector('.studio-canvas-column').getBoundingClientRect();
    return { sidebar: document.querySelector('.studio-sidebar'), history: document.querySelector('[role="tab"]'), chat: Math.round(chat.width), chatLeft: chat.x < canvas.x, font: getComputedStyle(document.querySelector('.compor-studio')).fontFamily, layout: document.querySelector('.compor-studio').dataset.layout, images: Array.from(document.querySelectorAll('.compor-studio img')).map(image => ({ src: image.getAttribute('src'), loaded: image.complete && image.naturalWidth > 0 })) };
  });
  assert.equal(geometry.sidebar, null);
  assert.equal(geometry.history, null);
  assert.equal(geometry.chat, 380);
  assert.equal(geometry.chatLeft, true);
  assert.equal(geometry.layout, 'b');
  assert.match(geometry.font, /Compor DM Sans/);
  assert.ok(geometry.images.every(image => image.loaded && image.src.startsWith('/studio/')));
  for (const name of ['brand-symbol.svg', 'brand-wordmark.svg', 'dot.svg', 'compor-avatar.svg']) assert.ok((await readFile(new URL(`../public/studio/${name}`, import.meta.url))).length > 100);
  const yellow = 'rgb(246, 213, 80)';
  const buttons = await page.locator('button').evaluateAll(nodes => nodes.map(button => ({ name: button.innerText.trim(), color: getComputedStyle(button).backgroundColor })));
  assert.equal(buttons.find(button => button.name === 'Baixar').color, yellow);
  assert.ok(buttons.filter(button => button.name !== 'Baixar').every(button => button.color !== yellow));
  await page.getByRole('button', { name: 'Aumentar zoom' }).click();
  await page.getByRole('button', { name: 'Restaurar zoom a 100%' }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Restaurar zoom a 100%' }).innerText(), '110%');
  await page.getByRole('button', { name: 'Ver quadro todo' }).click();
  assert.notEqual(await page.getByRole('button', { name: 'Restaurar zoom a 100%' }).innerText(), '110%');
  await page.getByRole('button', { name: 'Restaurar zoom a 100%' }).click();
  await page.getByRole('button', { name: 'Divulgar meu curso' }).click();
  assert.equal(await page.getByLabel('Sua mensagem').inputValue(), 'Quero divulgar meu curso.');
  const before = await page.locator('.studio-canvas-column').boundingBox();
  await page.getByRole('button', { name: 'Bases (3)', exact: true }).click();
  await page.getByRole('dialog', { name: 'Bases' }).waitFor();
  const during = await page.locator('.studio-canvas-column').boundingBox();
  assert.equal(Math.round(before.x), Math.round(during.x));
  assert.equal(Math.round(before.width), Math.round(during.width));
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog', { name: 'Bases' }).count(), 0);
  await page.getByRole('button', { name: 'Marca', exact: true }).click();
  await page.getByRole('dialog', { name: 'Marca' }).waitFor();
  await page.mouse.click(during.x + 40, during.y + 80);
  assert.equal(await page.getByRole('dialog', { name: 'Marca' }).count(), 0);
  await page.getByRole('button', { name: 'Planilhas para a rotina', exact: true }).click();
  await page.getByRole('button', { name: 'Outro projeto', exact: true }).click();
  await page.getByRole('button', { name: 'Outro projeto', exact: true }).click();
  await page.getByLabel('Renomear').fill('Projeto renomeado');
  await page.getByRole('button', { name: 'Salvar nome', exact: true }).click();
  await page.getByRole('button', { name: 'Projeto renomeado', exact: true }).waitFor();
  await page.screenshot({ path: '/tmp/compor-layout-b.png', fullPage: false });
  await page.getByRole('button', { name: 'Recolher conversa', exact: true }).click();
  await page.getByRole('button', { name: 'Abrir conversa', exact: true }).waitFor();
  assert.equal(await page.locator('.compor-studio').getAttribute('data-layout'), 'c');
  const collapsedWidth = await page.locator('.studio-canvas-column').evaluate(element => element.getBoundingClientRect().width);
  assert.ok(collapsedWidth > 1200);
  await page.screenshot({ path: '/tmp/compor-layout-c.png', fullPage: false });
  await page.reload();
  await page.getByRole('button', { name: 'Abrir conversa', exact: true }).waitFor();
  assert.equal(await page.locator('.compor-studio').getAttribute('data-layout'), 'c');
  await page.getByRole('button', { name: 'Abrir conversa', exact: true }).click();
  await page.getByRole('complementary', { name: 'Conversa com a IA' }).waitFor();
  assert.equal(await page.locator('.compor-studio').getAttribute('data-layout'), 'b');
  await page.getByRole('button', { name: 'Ver arte', exact: true }).click();
  assert.equal(await page.locator('.compor-studio').getAttribute('data-art'), 'open');
  assert.equal(await page.locator('.compor-studio').getAttribute('data-layout'), 'c');
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.compor-studio').getAttribute('data-art'), 'closed');
  assert.equal(await page.locator('.compor-studio').getAttribute('data-layout'), 'c');
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  const marca = await page.getByRole('button', { name: 'Marca', exact: true }).boundingBox();
  assert.ok(marca.x >= 0 && marca.x + marca.width <= 390);
  await page.screenshot({ path: '/tmp/compor-layout-mobile.png', fullPage: false });
  assert.deepEqual(errors, []);
});
