import test from 'node:test';
import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import { mkdir, writeFile, rm, readFile } from 'node:fs/promises';
import { spawn } from 'node:child_process';
import { once } from 'node:events';
import { createServer } from 'node:net';
import { chromium } from 'playwright-core';

const browserPath = process.env.BROWSER_EXECUTABLE_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const fixture = new URL('../app/studio-visual-test/', import.meta.url);
const pageSource = `'use client';
import {useState} from 'react';
import StudioShell,{CreativeBoard,StudioEmptyBoard,StudioChatPanel} from '../studio-shell';
export default function Preview(){
 const [stage,setStage]=useState('studio'),[tab,setTab]=useState('post'),[message,setMessage]=useState('');
 return <StudioShell stage={stage} projectTitle="Planilhas para a rotina" pieceSubtitle="Post para divulgar seu curso / 1080 × 1350" activeTab={tab} onNavigate={setStage} onTabChange={setTab} canOpenStudio userLabel="Mavi Almeida" onReview={()=>setStage('review')} footer="Alterações ainda locais no navegador" canvas={<CreativeBoard title={tab==='post'?'Vamos encontrar a sua direção.':tab==='history'?'Histórico de versões':tab==='facts'?'Fatos e textos':'Seu moodboard'}><StudioEmptyBoard onStartIdea={()=>setMessage('Quero divulgar meu curso.')} onAddReference={()=>setTab('moodboard')}/></CreativeBoard>} chat={<StudioChatPanel composer={<form onSubmit={event=>{event.preventDefault();setMessage('Enviada');}}><label className="studio-hint" htmlFor="test-message">Sua mensagem</label><textarea id="test-message" value={message} onChange={event=>setMessage(event.target.value)} placeholder="Peça um ajuste ou conte uma ideia…"/><div className="studio-composer-actions"><span className="studio-hint">Referências locais</span><button className="studio-button">Enviar</button></div></form>}><div className="studio-message" data-role="assistant"><span className="studio-message-label">Compor</span><p>O que você quer criar hoje? Pode me contar do seu jeito.</p></div></StudioChatPanel>}><p>Conteúdo da etapa {stage}</p></StudioShell>;
}`;

test('shell usa ativos originais, mantém navegação por teclado e permite explorar o quadro', { skip: !existsSync(browserPath) }, async t => {
  assert.equal(existsSync(fixture), false);
  await mkdir(fixture);
  await writeFile(new URL('page.jsx', fixture), pageSource);
  t.after(() => rm(fixture, { recursive: true, force: true }));
  const socket = createServer();
  await new Promise(resolve => socket.listen(0, '127.0.0.1', resolve));
  const port = socket.address().port;
  await new Promise(resolve => socket.close(resolve));
  const origin = `http://127.0.0.1:${port}`;
  const server = spawn(process.execPath, ['node_modules/next/dist/bin/next', 'dev', '-p', String(port), '-H', '127.0.0.1'], { stdio: 'ignore', env: { ...process.env, SUPABASE_URL: '', SUPABASE_PUBLISHABLE_KEY: '' } });
  t.after(async () => { if (server.exitCode === null && server.signalCode === null) { server.kill('SIGTERM'); await once(server, 'exit'); } });
  const deadline = Date.now() + 30000;
  while (true) { try { if ((await fetch(origin)).ok) break; } catch {} if (Date.now() > deadline) throw Error('Next não iniciou.'); await new Promise(resolve => setTimeout(resolve, 200)); }
  const browser = await chromium.launch({ executablePath: browserPath, headless: true });
  t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${origin}/studio-visual-test`);
  await page.getByRole('heading', { name: 'Vamos encontrar a sua direção.' }).waitFor();
  await page.evaluate(() => document.fonts.ready);
  const geometry = await page.evaluate(() => ({ sidebar: document.querySelector('.studio-sidebar').getBoundingClientRect().width, chat: document.querySelector('.studio-conversation').getBoundingClientRect().width, header: document.querySelector('.studio-project-header').getBoundingClientRect().height, font: getComputedStyle(document.querySelector('.compor-studio')).fontFamily, images: Array.from(document.querySelectorAll('.compor-studio img')).map(image => ({ src: image.getAttribute('src'), loaded: image.complete && image.naturalWidth > 0 })) }));
  assert.equal(geometry.sidebar, 184);
  assert.equal(geometry.chat, 424);
  assert.equal(geometry.header, 80);
  assert.match(geometry.font, /Compor DM Sans/);
  assert.ok(geometry.images.every(image => image.loaded && image.src.startsWith('/studio/')));
  for (const name of ['brand-symbol.svg', 'brand-wordmark.svg', 'folder.svg', 'image.svg', 'history.svg', 'dot.svg', 'compor-avatar.svg']) assert.ok((await readFile(new URL(`../public/studio/${name}`, import.meta.url))).length > 100);
  await page.getByRole('tab', { name: 'Estúdio', exact: true }).focus();
  await page.keyboard.press('ArrowRight');
  assert.equal(await page.getByRole('tab', { name: 'Referências' }).getAttribute('aria-selected'), 'true');
  await page.getByRole('tab', { name: 'Estúdio', exact: true }).click();
  await page.getByRole('button', { name: 'Aumentar zoom' }).click();
  await page.getByRole('button', { name: 'Restaurar zoom a 100%' }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Restaurar zoom a 100%' }).innerText(), '110%');
  await page.getByRole('button', { name: 'Ver quadro todo' }).click();
  assert.notEqual(await page.getByRole('button', { name: 'Restaurar zoom a 100%' }).innerText(), '110%');
  await page.getByRole('button', { name: 'Restaurar zoom a 100%' }).click();
  await page.getByRole('button', { name: 'Divulgar meu curso' }).click();
  assert.equal(await page.getByLabel('Sua mensagem').inputValue(), 'Quero divulgar meu curso.');
  await page.screenshot({ path: '/tmp/compor-studio-shell-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await page.getByRole('button', { name: 'Versões', exact: true }).click();
  await page.getByRole('heading', { name: 'Histórico de versões' }).waitFor();
  const selected = await page.getByRole('tab', { name: 'Histórico', exact: true }).boundingBox();
  assert.ok(selected.x >= 0 && selected.x + selected.width <= 390);
  const emptyCard = await page.locator('.studio-empty-board').boundingBox();
  assert.ok(emptyCard.x >= 0 && emptyCard.x + emptyCard.width <= 390);
  await page.screenshot({ path: '/tmp/compor-studio-shell-mobile.png', fullPage: true });
  assert.deepEqual(errors, []);
});
