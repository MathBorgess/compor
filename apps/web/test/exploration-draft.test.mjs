import test from 'node:test';
import assert from 'node:assert/strict';
import {createStudioState,createPost,parseStudioState,editDraft,recordSavedVersion} from '../lib/studio-state.ts';
import {confirmedExploration,recordCompletedExploration,prepareExplorationDraft} from '../lib/exploration-draft.ts';
import {selectScopedReference,updatePostContext} from '../lib/studio-post-context.ts';
import {prepareReferenceWorkspace,startPostPreparation,updatePostPreparation,completePostPreparation,updateWorkflow} from '../lib/studio-workflow.ts';
const id=n=>`00000000-0000-4000-8000-${String(n).padStart(12,'0')}`;
const scope={userId:id(1),projectId:id(2)};
const source=(n,ordinal=n)=>({imageId:id(n),ordinal});
const initial=()=>createPost(createStudioState(scope),{pieceId:id(3)});
function harness(input,{existing=false,rows,fetchImage=true}={}){
 let state=input,asset=existing?new Blob(['existing'],{type:'image/png'}):null,readCount=0;
 const bytes=new Blob([new Uint8Array([137,80,78,71,13,10,26,10,1])],{type:'image/png'});
 const options={conversationId:'references',getState:()=>state,change:reducer=>{state=reducer(state);return state;},flush:async()=>{},storage:{getDraftAsset:async()=>asset?{file:asset}:null,putDraftAsset:async value=>{assert.equal(value.ifAbsent,true);assert.equal(value.expectedRevision,state.revision);if(asset){const error=Error();error.code='studio_draft_asset_exists';throw error;}asset=value.file;}},fetcher:async url=>{readCount++;if(url.startsWith('/api/studio/explorations?'))return Response.json({images:rows??[{id:id(12),project_id:id(2),state:'completed',ordinal:12}]});return fetchImage?new Response(bytes,{headers:{'content-type':'image/png'}}):new Response('',{status:503});}};
 return {options,getState:()=>state,asset:()=>asset,reads:()=>readCount,bytes};
}
test('last confirmed proposal is recorded per conversation and round-trips without selecting or approving it',()=>{
 let state=recordCompletedExploration(initial(),'references',source(11));
 state=recordCompletedExploration(state,'references',source(12));
 state=recordCompletedExploration(state,'references',source(10));
 state=recordCompletedExploration(state,id(3),source(20));
 assert.deepEqual(state.workflow.latestExplorations.references,source(12));
 assert.deepEqual(state.workflow.latestExplorations[id(3)],source(20));
 assert.deepEqual(parseStudioState(JSON.parse(JSON.stringify(state))),state);
 assert.deepEqual(state.references,[]);assert.equal(state.drafts[0].approval.status,'unapproved');
 assert.throws(()=>recordCompletedExploration(state,id(99),source(30)));
});
test('the latest completed generated bytes become v0 and persist provenance, independent of references',async()=>{
 const h=harness(recordCompletedExploration(initial(),'references',source(12)));
 assert.equal(await prepareExplorationDraft(h.options),'retained');
 assert.deepEqual(new Uint8Array(await h.asset().arrayBuffer()),new Uint8Array(await h.bytes.arrayBuffer()));
 const draft=parseStudioState(JSON.parse(JSON.stringify(h.getState()))).drafts[0];
 assert.equal(draft.baseVersion,0);assert.equal(draft.expectedLatestVersion,0);assert.equal(draft.approval.status,'unapproved');
 assert.deepEqual(draft.creationContext.explorationSource,{projectId:id(2),conversationId:'references',...source(12)});
 assert.deepEqual(draft.creationContext.references,[]);
});
test('no generation, existing artwork, edited drafts and saved versions are left intact',async()=>{
 const empty=harness(initial());assert.equal(await prepareExplorationDraft(empty.options),'none');assert.equal(empty.reads(),0);
 const candidate=recordCompletedExploration(initial(),'references',source(12));
 const existing=harness(candidate,{existing:true});assert.equal(await prepareExplorationDraft(existing.options),'preserved');assert.equal(existing.reads(),0);
 const edited=harness(editDraft(candidate,{field:'caption',value:'Minha legenda'}));assert.equal(await prepareExplorationDraft(edited.options),'preserved');assert.equal(edited.reads(),0);
 const saved=recordSavedVersion(candidate,{pieceId:id(3),baseVersion:0,version:1,content:candidate.drafts[0].content,eventId:id(30)});
 const version=harness(saved);assert.equal(await prepareExplorationDraft(version.options),'preserved');assert.equal(version.reads(),0);
});
test('another post, running and unknown results never become v0',async()=>{
 const state=recordCompletedExploration(initial(),id(3),source(12));
 const other=harness(state);assert.equal(await prepareExplorationDraft(other.options),'none');assert.equal(other.reads(),0);
 for(const value of ['running','unknown','rejected']){
  const h=harness(recordCompletedExploration(initial(),'references',source(12)),{rows:[{id:id(12),project_id:id(2),state:value,ordinal:12}]});
  await assert.rejects(prepareExplorationDraft(h.options));assert.equal(h.asset(),null);
 }
});
test('image retrieval failure and mid-flight draft edits preserve work',async()=>{
 const h=harness(recordCompletedExploration(initial(),'references',source(12)),{fetchImage:false});
 await assert.rejects(prepareExplorationDraft(h.options));assert.equal(h.asset(),null);
 const changed=harness(recordCompletedExploration(initial(),'references',source(12)));
 const fetcher=changed.options.fetcher;changed.options.fetcher=async url=>{const response=await fetcher(url);if(url.includes('/image?'))changed.options.change(value=>editDraft(value,{field:'caption',value:'não substituir'}));return response;};
 assert.equal(await prepareExplorationDraft(changed.options),'preserved');assert.equal(changed.asset(),null);
});
test('text-only exploration retains context but never credits selected images before or after generation',async()=>{
 const reference=n=>({id:id(n),name:`Imagem ${n}`,mime:'image/png',size:20,width:1,height:1});
 const creationContext={postContext:{objective:'Autoridade',message:'Mensagem original',action:''},references:[reference(40)]};
 let state=recordCompletedExploration(initial(),'references',{...source(12),creationContext});
 state=selectScopedReference(state,reference(41),'references');
 state=updatePostContext(state,id(3),{message:'Mensagem escolhida depois'});
 const h=harness(state);assert.equal(await prepareExplorationDraft(h.options),'retained');
 const context=h.getState().drafts[0].creationContext;
 assert.deepEqual(context.references,[]);assert.equal(context.postContext.message,'Mensagem original');
 assert.equal(h.getState().posts[id(3)].message,'Mensagem escolhida depois');
});
test('a newer completion while loading the image prevents retaining the older proposal',async()=>{
 const h=harness(recordCompletedExploration(initial(),'references',source(12)));
 const original=h.options.fetcher;
 h.options.fetcher=async url=>{const response=await original(url);if(url.includes('/image?'))h.options.change(state=>recordCompletedExploration(state,'references',source(13)));return response;};
 await assert.rejects(prepareExplorationDraft(h.options),/exploration_changed/);assert.equal(h.asset(),null);
 assert.equal(h.getState().workflow.latestExplorations.references.ordinal,13);
});
test('an older scoped candidate is confirmed after newer images from other posts',async()=>{
 const urls=[];
 const fetcher=async url=>{urls.push(url);return Response.json(url.includes('beforeOrdinal=100')?{images:[{id:id(12),project_id:id(2),state:'completed',ordinal:12}],nextBeforeOrdinal:null}:{images:[{id:id(200),project_id:id(2),state:'completed',ordinal:200}],nextBeforeOrdinal:100});};
 assert.deepEqual(await confirmedExploration(id(2),id(12),fetcher),source(12));assert.equal(urls.length,2);
 const h=harness(recordCompletedExploration(initial(),'references',source(12)));await prepareExplorationDraft(h.options);assert.equal(h.getState().drafts[0].creationContext.explorationSource.ordinal,12);
});
test('an internal reference workspace is never seeded; only the explicitly completed named post receives v0',async()=>{
 let state=recordCompletedExploration(prepareReferenceWorkspace(createStudioState({...scope,prepare:true}),id(3)),'references',source(12));
 state=updateWorkflow(state,{referenceHandoff:'references'});
 const internal=harness(state);assert.equal(await prepareExplorationDraft(internal.options),'preserved');assert.equal(internal.reads(),0);assert.equal(internal.asset(),null);
 state=updatePostPreparation(startPostPreparation(state,id(4)),{name:'Convite para colaborar',message:'Mensagem do post'});
 assert.equal(state.drafts.some(draft=>draft.pieceId===id(4)),false);
 state=completePostPreparation(state);
 const confirmed=harness(state);assert.equal(await prepareExplorationDraft(confirmed.options),'retained');
 assert.equal(confirmed.getState().selection.pieceId,id(4));assert.equal(confirmed.getState().posts[id(4)].name,'Convite para colaborar');assert.equal(confirmed.getState().drafts.find(draft=>draft.pieceId===id(3)).creationContext,undefined);
});
