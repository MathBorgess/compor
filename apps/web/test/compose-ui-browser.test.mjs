import test from 'node:test';
import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import { readFile } from 'node:fs/promises';
import { spawn } from 'node:child_process';
import { once } from 'node:events';
import { createServer } from 'node:net';
import { chromium } from 'playwright-core';
const browserPath = process.env.BROWSER_EXECUTABLE_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';

test('upload autorizado e textos editáveis geram e baixam PNG local sem rede externa', { skip: !existsSync(browserPath) }, async t => {
  const socket = createServer(); await new Promise(resolve => socket.listen(0, '127.0.0.1', resolve));
  const port = socket.address().port; await new Promise(resolve => socket.close(resolve));
  const origin = `http://127.0.0.1:${port}`;
  const child = spawn(process.execPath, ['node_modules/next/dist/bin/next', 'dev', '-p', String(port), '-H', '127.0.0.1'], { stdio: 'ignore', env: { ...process.env, SUPABASE_URL: 'https://example.supabase.co', SUPABASE_PUBLISHABLE_KEY: 'sb_publishable_publictest', APP_ORIGIN: origin } });
  t.after(async () => { if (child.exitCode === null && child.signalCode === null) { child.kill('SIGTERM'); await once(child, 'exit'); } });
  const deadline = Date.now() + 30000;
  while (true) { try { if ((await fetch(origin)).ok) break; } catch {} if (Date.now() > deadline) throw new Error('aplicação indisponível'); await new Promise(resolve => setTimeout(resolve, 200)); }
  const browser = await chromium.launch({ executablePath: browserPath, headless: true }); t.after(() => browser.close());
  const page = await browser.newPage({ acceptDownloads: true });
  const external = []; let pieceWrites = 0;
  page.on('request', request => { if (!request.url().startsWith(origin) && !request.url().startsWith('blob:')) external.push(request.url()); });
  let userId = 'alice';
  await page.route('**/auth/session', route => route.fulfill({ json: { state: 'connected', userId } }));
  await page.route('**/api/projects', route => route.fulfill({ json: { projects: [{ id: '11111111-1111-4111-8111-111111111111', title: 'Oficina', created_at: '2026-11-03T00:00:00Z' }, { id: '22222222-2222-4222-8222-222222222222', title: 'Café', created_at: '2026-11-03T00:00:00Z' }] } }));
  await page.route('**/api/pieces*', route => { if (route.request().method() !== 'GET') pieceWrites++; return route.fulfill({ json: { versions: [] } }); });
  await page.goto(origin);
  await page.getByRole('button', { name: 'Abrir Oficina' }).click();
  await page.getByRole('button', { name: 'Nova peça' }).click();
  await page.getByLabel('Título da peça').fill('Primeiro título');
  await page.getByLabel('Legenda').fill('Legenda continua editável');
  const pixels = await page.evaluate(async () => {
    const canvas = document.createElement('canvas'); canvas.width = 256; canvas.height = 256;
    const ctx = canvas.getContext('2d'); ctx.fillStyle = '#3977aa'; ctx.fillRect(0, 0, 256, 256);
    return Array.from(new Uint8Array(await (await new Promise(resolve => canvas.toBlob(resolve, 'image/png'))).arrayBuffer()));
  });
  await page.getByLabel('Imagem-base PNG').setInputFiles({ name: 'base.png', mimeType: 'image/png', buffer: Buffer.from(pixels) });
  assert.equal(await page.getByRole('button', { name: 'Gerar prévia PNG' }).isDisabled(), true);
  await page.getByLabel('Tenho autorização para usar esta imagem').check();
  await page.getByRole('button', { name: 'Gerar prévia PNG' }).click();
  const preview = page.getByRole('img', { name: 'Prévia da peça' }); await preview.waitFor();
  const first = await preview.getAttribute('src');
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Baixar PNG' }).click();
  const file = await readFile(await (await downloadPromise).path());
  assert.deepEqual([...file.subarray(0, 8)], [137,80,78,71,13,10,26,10]);
  await page.getByLabel('Título da peça').fill('Outro título');
  assert.equal(await preview.count(), 0);
  await page.getByRole('button', { name: 'Gerar prévia PNG' }).click();
  await preview.waitFor();
  assert.notEqual(await preview.getAttribute('src'), first);
  const secondDownload = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Baixar PNG' }).click();
  const secondFile = await readFile(await (await secondDownload).path());
  assert.notDeepEqual(secondFile, file, 'alteração no texto deve alterar os pixels exportados');
  assert.equal(await page.getByLabel('Legenda').inputValue(), 'Legenda continua editável');
  await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  await page.getByText('Imagem carregada: base.png').waitFor();
  assert.equal(await page.getByLabel('Tenho autorização para usar esta imagem').isChecked(), true);
  await page.getByRole('button', { name: 'Abrir Café' }).click();
  await page.getByRole('button', { name: 'Nova peça' }).click();
  assert.equal(await page.getByText('Imagem carregada: base.png').count(), 0);
  assert.equal(await page.getByLabel('Tenho autorização para usar esta imagem').isDisabled(), true);
  await page.getByRole('button', { name: 'Abrir Oficina' }).click();
  await page.getByText('Imagem carregada: base.png').waitFor();
  userId = 'bob';
  await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  await page.getByRole('button', { name: 'Abrir Oficina' }).waitFor();
  await page.getByRole('button', { name: 'Abrir Oficina' }).click();
  await page.getByRole('button', { name: 'Nova peça' }).click();
  assert.equal(await page.getByText('Imagem carregada: base.png').count(), 0);
  userId = 'alice';
  await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  await page.getByText('Imagem carregada: base.png').waitFor();
  await page.getByLabel('Imagem-base PNG').setInputFiles({ name: 'falso.png', mimeType: 'image/png', buffer: Buffer.from('não é PNG') });
  await page.getByLabel('Tenho autorização para usar esta imagem').check();
  await page.getByRole('button', { name: 'Gerar prévia PNG' }).click();
  await page.getByText(/Não foi possível compor a imagem/).waitFor();
  assert.equal(await page.getByRole('link', { name: 'Baixar PNG' }).count(), 0);
  assert.match(await page.locator('body').innerText(), /não representa aprovação/i);
  assert.equal(pieceWrites, 0);
  assert.deepEqual(external, []);
});
