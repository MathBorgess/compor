import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';

const user='11111111-1111-4111-8111-111111111111',other='aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa',project='22222222-2222-4222-8222-222222222222',piece='33333333-3333-4333-8333-333333333333';
test('listagem invocadora respeita RLS mesmo sob política ampla e percorre todas as páginas',async t=>{
 const db=new PGlite();t.after(()=>db.close());
 await db.exec(`create role authenticated;create role anon;create schema auth;create schema storage;
 create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
 grant usage on schema auth,storage,public to public;grant execute on function auth.uid() to public;
 create table public.projects(id uuid primary key,owner_id uuid not null);
 create table public.piece_versions(project_id uuid not null,piece_id uuid not null,version integer not null);
 grant select on public.projects,public.piece_versions to authenticated;
 alter table public.projects enable row level security;alter table public.piece_versions enable row level security;
 create policy project_owner on public.projects for select to authenticated using(owner_id=auth.uid());
 create policy version_owner on public.piece_versions for select to authenticated using(exists(select 1 from public.projects p where p.id=project_id and p.owner_id=auth.uid()));
 create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
 create table storage.objects(bucket_id text not null,name text not null,primary key(bucket_id,name));
 alter table storage.objects enable row level security;grant select on storage.objects to authenticated,anon;
 create policy broad_previous on storage.objects for select to public using(true);`);
 await db.exec(await readFile(new URL('../../../supabase/migrations/20261103000003_private_project_images.sql',import.meta.url),'utf8'));
 await db.exec(await readFile(new URL('../../../supabase/migrations/20261103000010_list_piece_image_assets.sql',import.meta.url),'utf8'));
 await db.query('insert into public.projects values($1,$2)',[project,user]);
 await db.query('insert into public.piece_versions values($1,$2,1),($1,$2,2)',[project,piece]);
 const assets=Array.from({length:53},(_,i)=>`44444444-4444-4444-8444-${String(i+1).padStart(12,'0')}`);
 for(const id of assets)await db.query('insert into storage.objects values($1,$2)',['compor-project-images',`${user}/${project}/${piece}/1/${id}.png`]);
 await db.query('insert into storage.objects values($1,$2)',['compor-project-images',`${user}/${project}/${piece}/2/55555555-5555-4555-8555-555555555555.png`]);
 await db.exec(`set role authenticated;select set_config('request.jwt.claim.sub','${user}',false)`);
 const query='select public.list_piece_image_assets($1,$2,$3,$4) as page';
 const first=(await db.query(query,[project,piece,1,null])).rows[0].page;
 assert.deepEqual(first.assets,assets.slice(0,50));assert.equal(first.nextCursor,assets[49]);
 const second=(await db.query(query,[project,piece,1,first.nextCursor])).rows[0].page;
 assert.deepEqual(second.assets,assets.slice(50));assert.equal(second.nextCursor,null);
 const wrongVersion=(await db.query(query,[project,piece,2,null])).rows[0].page;assert.equal(wrongVersion.assets.length,1);
 await db.exec(`select set_config('request.jwt.claim.sub','${other}',false)`);
 const denied=(await db.query(query,[project,piece,1,null])).rows[0].page;assert.deepEqual(denied,{assets:[],nextCursor:null});
 await db.exec('reset role;set role anon');
 await assert.rejects(()=>db.query(query,[project,piece,1,null]));
});
